import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%HELIX_AGENT_HOOK_PORT%"=="" if defined HELIX_AGENT_HOOK_ENDPOINT if exist "%HELIX_AGENT_HOOK_ENDPOINT%" call "%HELIX_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%HELIX_AGENT_HOOK_TOKEN%"=="" if not "%HELIX_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\helix-dev\\agent-hooks" for /r "%APPDATA%\\helix-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%HELIX_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\helix-dev-wt" for /d %%P in ("%APPDATA%\\helix-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%HELIX_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\helix\\agent-hooks" for /r "%APPDATA%\\helix\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%HELIX_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%HELIX_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set HELIX_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%HELIX_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__helix_read_ancestor_var() {',
    '  __helix_name="$1"',
    '  __helix_pid="${PPID:-}"',
    '  while [ -n "$__helix_pid" ] && [ "$__helix_pid" != "0" ] && [ "$__helix_pid" != "1" ]; do',
    '    __helix_value=""',
    '    if [ -r "/proc/$__helix_pid/environ" ]; then',
    '      __helix_value=$(tr "\\000" "\\n" < "/proc/$__helix_pid/environ" 2>/dev/null | sed -n "s/^${__helix_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__helix_value" ]; then',
    '      __helix_value=$(ps eww -p "$__helix_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__helix_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__helix_value" ]; then',
    '      printf "%s\\n" "$__helix_value"',
    '      return 0',
    '    fi',
    '    __helix_pid=$(ps -o ppid= -p "$__helix_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__helix_fill_from_ancestor() {',
    '  __helix_name="$1"',
    '  case "$__helix_name" in',
    '    HELIX_AGENT_HOOK_ENDPOINT) [ -z "${HELIX_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    HELIX_AGENT_HOOK_PORT) [ -z "${HELIX_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    HELIX_AGENT_HOOK_TOKEN) [ -z "${HELIX_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    HELIX_AGENT_HOOK_ENV) [ -z "${HELIX_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    HELIX_AGENT_HOOK_VERSION) [ -z "${HELIX_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    HELIX_PANE_KEY) [ -z "${HELIX_PANE_KEY:-}" ] || return 0 ;;',
    '    HELIX_TAB_ID) [ -z "${HELIX_TAB_ID:-}" ] || return 0 ;;',
    '    HELIX_WORKTREE_ID) [ -z "${HELIX_WORKTREE_ID:-}" ] || return 0 ;;',
    '    HELIX_AGENT_LAUNCH_TOKEN) [ -z "${HELIX_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __helix_value=$(__helix_read_ancestor_var "$__helix_name") || return 0',
    '  [ -n "$__helix_value" ] && export "$__helix_name=$__helix_value"',
    '}',
    '__helix_endpoint_value() {',
    '  __helix_endpoint_name="$1"',
    '  __helix_endpoint_path="$2"',
    '  sed -n "s/^${__helix_endpoint_name}=//p" "$__helix_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__helix_fill_from_endpoint_file() {',
    '  __helix_endpoint_path="$1"',
    '  [ -r "$__helix_endpoint_path" ] || return 0',
    '  __helix_endpoint_port=$(__helix_endpoint_value HELIX_AGENT_HOOK_PORT "$__helix_endpoint_path")',
    '  if [ -n "${HELIX_AGENT_HOOK_PORT:-}" ] && [ -n "$__helix_endpoint_port" ] && [ "$__helix_endpoint_port" != "$HELIX_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __helix_endpoint_name in HELIX_AGENT_HOOK_PORT HELIX_AGENT_HOOK_TOKEN HELIX_AGENT_HOOK_ENV HELIX_AGENT_HOOK_VERSION; do',
    '    eval "__helix_current=\\${$__helix_endpoint_name:-}"',
    '    [ -z "$__helix_current" ] || continue',
    '    __helix_endpoint_value=$(__helix_endpoint_value "$__helix_endpoint_name" "$__helix_endpoint_path")',
    '    [ -n "$__helix_endpoint_value" ] && export "$__helix_endpoint_name=$__helix_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __helix_name in HELIX_AGENT_HOOK_ENDPOINT HELIX_AGENT_HOOK_PORT HELIX_AGENT_HOOK_TOKEN HELIX_AGENT_HOOK_ENV HELIX_AGENT_HOOK_VERSION HELIX_PANE_KEY HELIX_TAB_ID HELIX_WORKTREE_ID HELIX_AGENT_LAUNCH_TOKEN; do',
    '  __helix_fill_from_ancestor "$__helix_name"',
    'done',
    'if [ -n "$HELIX_AGENT_HOOK_ENDPOINT" ] && [ -r "$HELIX_AGENT_HOOK_ENDPOINT" ]; then',
    '  __helix_fill_from_endpoint_file "$HELIX_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$HELIX_AGENT_HOOK_TOKEN" ] && [ -n "$HELIX_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/helix-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/helix-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/helix-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/helix-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/helix-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/helix-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/helix/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/helix/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^HELIX_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$HELIX_AGENT_HOOK_PORT" ]; then',
    '      __helix_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$HELIX_AGENT_HOOK_PORT" ] || [ -z "$HELIX_AGENT_HOOK_TOKEN" ] || [ -z "$HELIX_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${HELIX_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Helix-Agent-Hook-Token: ${HELIX_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${HELIX_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${HELIX_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${HELIX_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${HELIX_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${HELIX_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${HELIX_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
